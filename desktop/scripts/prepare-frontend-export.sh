#!/usr/bin/env bash
#
# Non-invasively produce a STATIC export of ../frontend for the Tauri bundle.
#
# Why a copy: the real ../frontend is a Next.js app configured for a server deployment
# (`output: "standalone"`) and it contains server-only route handlers (app/api/*). A static
# export (`output: "export"`) cannot include those route handlers. Rather than mutate the real
# frontend (which would break the web deployment), we build from a prepared COPY in which:
#   * app/api/* is removed        — the Rust proxy (src-tauri/src/proxy.rs) replaces it,
#   * output is set to "export",
#   * NEXT_PUBLIC_API_URL points the SPA at the mainaiapi: proxy scheme.
#
# The real ../frontend tree is never written to. Result: desktop/.app-build/out (git-ignored),
# referenced by src-tauri/tauri.conf.json as frontendDist.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # desktop/
SRC="$(cd "$HERE/../frontend" && pwd)"                     # ../frontend
BUILD="$HERE/.app-build"
WORK="$BUILD/src"
OUT="$BUILD/out"

# The origin the SPA will call. The webview issues fetch("mainaiapi://localhost/api/...") and
# the Tauri-registered scheme forwards it to the backend holding the HttpOnly session cookies.
API_ORIGIN="${MAINAI_API_ORIGIN:-mainaiapi://localhost}"

echo "[export] frontend source: $SRC"
echo "[export] api origin:      $API_ORIGIN"

# 1. Ensure the frontend's dependencies are installed (node_modules is git-ignored; this does
#    not change any tracked file in ../frontend).
if [ ! -x "$SRC/node_modules/.bin/next" ]; then
  echo "[export] installing frontend dependencies (npm ci)…"
  ( cd "$SRC" && npm ci )
fi

# 2. Fresh working copy (exclude heavy / server-only / test artifacts).
rm -rf "$WORK" "$OUT"
mkdir -p "$WORK"
rsync -a \
  --exclude 'node_modules' \
  --exclude '.next' \
  --exclude 'out' \
  --exclude 'e2e' \
  --exclude 'test-results' \
  --exclude 'playwright-report' \
  --exclude 'playwright*.config.ts' \
  --exclude '.git' \
  "$SRC/" "$WORK/"

# 3. Provide dependencies as a REAL directory inside the work tree. A symlink is rejected by
#    Next 16's Turbopack ("symlink points out of the filesystem root"), so clone them instead.
#    On APFS `cp -c` uses copy-on-write (near-instant, no extra disk); fall back to a plain copy.
if cp -Rc "$SRC/node_modules" "$WORK/node_modules" 2>/dev/null; then
  echo "[export] node_modules cloned (APFS copy-on-write)"
else
  echo "[export] clonefile unavailable; plain copy of node_modules…"
  cp -R "$SRC/node_modules" "$WORK/node_modules"
fi

# 4. Remove server-only / web-only routes that are incompatible with output: export and have
#    no meaning in a native bundle:
#      * app/api/*   — the same-origin proxy, replaced at runtime by the Rust proxy.
#      * app/robots.ts — a /robots.txt generator; irrelevant to an installed app.
rm -rf "$WORK/app/api"
rm -f "$WORK/app/robots.ts"

# 4b. Dynamic app-router routes ([id]) cannot be statically exported without a server-component
#     generateStaticParams(), and these pages are client components ("use client"), so they
#     can't host one. For this foundation milestone the single such route — the library detail
#     view — is deferred (the library LIST and every other route work). Follow-up: refactor it
#     to a query-param page (/library?id=) or add an SPA fallback. Fail loudly if a NEW,
#     undeclared dynamic route appears so this decision stays visible.
KNOWN_DEFERRED="app/(shell)/library/[id]"
rm -rf "$WORK/$KNOWN_DEFERRED"
UNEXPECTED="$(cd "$WORK" && find app -type d -name '*[[]*' 2>/dev/null || true)"
if [ -n "$UNEXPECTED" ]; then
  echo "[export] FATAL: unexpected dynamic route(s) not handled for static export:" >&2
  echo "$UNEXPECTED" >&2
  echo "[export] add a static-export strategy (generateStaticParams/query-param/SPA-fallback) before shipping." >&2
  exit 1
fi

# 5. Static-export Next config for this build only (the real next.config.mjs is untouched).
cat > "$WORK/next.config.mjs" <<'EOF'
/** @type {import('next').NextConfig} */
// Generated by desktop/scripts/prepare-frontend-export.sh for the Tauri static bundle ONLY.
// The real frontend/next.config.mjs (server "standalone"/Vercel) is not modified.
const nextConfig = {
  output: "export",
  images: { unoptimized: true },
  trailingSlash: true,
};
export default nextConfig;
EOF

# 6. Build the static export. NEXT_PUBLIC_API_URL is inlined into the client bundle so every
#    api call targets the mainaiapi: proxy scheme instead of a (nonexistent) same-origin server.
echo "[export] running next build (output: export)…"
(
  cd "$WORK"
  NEXT_PUBLIC_API_URL="$API_ORIGIN" ./node_modules/.bin/next build
)

# Guard: a static export must have produced out/index.html. Fail loudly otherwise so a broken
# build can never be mistaken for a working one.
if [ ! -f "$WORK/out/index.html" ]; then
  echo "[export] FATAL: next export did not produce out/index.html" >&2
  exit 1
fi

# 7. Publish the export to the frontendDist location.
mkdir -p "$OUT"
rsync -a --delete "$WORK/out/" "$OUT/"

echo "[export] done -> $OUT"
ls -1 "$OUT" | head -20
